#!/bin/sh
# Проверка бота после выкатки. Кладётся в артефакт как `verify`, запускается
# выкаткой (deploy-kit, release.sh) сразу после переключения current.
#
# HTTP-проверка боту неприменима: он никуда не слушает, а сам ходит в Telegram
# длинным опросом. Единственный способ убедиться, что он работает, — заставить
# его сделать ровно то, ради чего он существует: прочитать данные агента и
# отправить владельцу сводку. Это и делает -selftest.
#
# Запускаем через systemd-run, а не напрямую: токен лежит в EnvironmentFile с
# правами 0600, а сам бот работает под своим пользователем. Повторять здесь
# оба этих условия руками значило бы проверять не то, что поедет.
#
# --wait возвращает код выхода самой команды, поэтому провал selftest
# становится провалом выкатки и приводит к откату.

set -eu

exec systemd-run \
    --wait --quiet --collect \
    --unit="samoylove-bot-selftest-$$" \
    --uid=samoylove-bot \
    --property=EnvironmentFile=/etc/samoylove-bot/env \
    /opt/samoylove-bot/current/samoylove-bot -selftest
